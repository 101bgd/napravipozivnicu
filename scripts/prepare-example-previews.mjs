import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { createServer } from 'vite';
import { chromium } from 'playwright';
import { templates } from '../src/templates.js';
import { CATEGORY_CONTENT } from '../src/seo-content.js';
const root = fileURLToPath(new URL('../', import.meta.url));
const { alts } = JSON.parse(await fs.readFile(path.join(root, 'content/image-seo/alts.json'), 'utf8'));
const directory = 'assets/pozivnice/primeri';
await fs.mkdir(path.join(root, 'public', directory), { recursive: true });
const server = await createServer({ root, server: { host: '127.0.0.1', port: 5196, strictPort: true } });
let browser;
const previews = {}, report = [];
try {
  await server.listen();
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
  const page = await browser.newPage();
  await page.goto('http://127.0.0.1:5196/');
  for (const template of templates) {
    const dataUrl = await page.evaluate(async template => {
      const { renderInvitation } = await import('/src/render.js');
      return renderInvitation(document.createElement('canvas'), template, undefined, null, 500).toDataURL('image/webp', .86);
    }, template);
    const bytes = Buffer.from(dataUrl.split(',')[1], 'base64');
    const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 12);
    const name = `${CATEGORY_CONTENT[template.category].slug}-${template.id}-${hash}.webp`;
    await fs.writeFile(path.join(root, 'public', directory, name), bytes);
    previews[template.id] = { thumbnail: `/${directory}/${name}`, imageAlt: alts[template.id] };
    report.push({ id: template.id, bytes: bytes.length, width: 500, height: 700 });
  }
} finally { await browser?.close(); await server.close(); }
await fs.writeFile(path.join(root, 'src/example-previews.js'), `// Generated by scripts/prepare-example-previews.mjs.\nexport const examplePreviews = ${JSON.stringify(previews, null, 2)};\n`);
await fs.writeFile(path.join(root, 'content/image-seo/example-previews.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report));
