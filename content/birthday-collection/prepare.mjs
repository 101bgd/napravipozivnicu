// The uploaded originals match birthday-batch byte-for-byte. Reuse its WebP backgrounds.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash, randomUUID } from 'node:crypto';
import { createServer } from 'vite';
import { chromium } from 'playwright';
import { jsPDF } from 'jspdf';
import { birthdayCollectionDrafts, birthdayCollectionDesign } from './designs.mjs';
import { birthdayAssetIds, birthdayAssets } from '../../src/birthday-assets.js';
import { baptismAssetIds } from '../../src/baptism-assets.js';

const directory = fileURLToPath(new URL('./', import.meta.url)), root = path.resolve(directory, '../..');
const artifacts = path.resolve(root, '../artifacts/birthday-collection');
const assetDirectory = 'assets/pozivnice/deciji-rodjendani-kolekcija';
await fs.mkdir(path.join(root, 'public', assetDirectory), { recursive: true });
await fs.mkdir(artifacts, { recursive: true });
let ids;
try { ids = JSON.parse(await fs.readFile(path.join(directory, 'asset-ids.json'), 'utf8')); } catch {
  ids = { fonts: { ...birthdayAssetIds.fonts, hand: baptismAssetIds.fonts.marckscript }, designs: Object.fromEntries(birthdayCollectionDrafts.map(draft => [draft.id, { background: birthdayAssetIds.designs[draft.backgroundSource].background, thumbnail: randomUUID() }])) };
}
const assets = [], catalog = [], reports = [];
const server = await createServer({ root, server: { host: '127.0.0.1', port: 5194, strictPort: true } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
  const page = await browser.newPage();
  await page.goto('http://127.0.0.1:5194/pozivnice/');
  for (const draft of birthdayCollectionDrafts) {
    const backgroundUrl = birthdayAssets.get(ids.designs[draft.id].background);
    const design = birthdayCollectionDesign(draft.id, { backgroundId: ids.designs[draft.id].background, fontIds: ids.fonts });
    const result = await page.evaluate(async ({ design, backgroundUrl }) => {
      await import('/src/editor.js');
      const { renderDesign, designData, loadDesignFont } = await import('/src/design-renderer.js');
      await Promise.all(design.fonts.map(font => loadDesignFont(font)));
      await Promise.all(design.layers.map(l => document.fonts.load(`${l.italic ? 'italic ' : ''}${l.bold ? '700 ' : '400 '}${l.size}px "${l.family}"`, l.text)));
      const image = new Image(); image.src = backgroundUrl; await image.decode();
      const data = designData(design), assets = { background: image };
      return {
        full: renderDesign(document.createElement('canvas'), design, data, null, 1500, assets).toDataURL('image/png'),
        thumbnail: renderDesign(document.createElement('canvas'), design, data, null, 500, assets).toDataURL('image/webp', .86),
        width: image.naturalWidth, height: image.naturalHeight,
      };
    }, { design, backgroundUrl });
    const decode = value => Buffer.from(value.split(',')[1], 'base64');
    const thumbnail = decode(result.thumbnail), hash = createHash('sha256').update(thumbnail).digest('hex').slice(0, 12);
    const thumbnailUrl = `/${assetDirectory}/${draft.id}-pregled-${hash}.webp`;
    await fs.writeFile(path.join(root, 'public', thumbnailUrl), thumbnail);
    assets.push([ids.designs[draft.id].thumbnail, thumbnailUrl]);
    const { source, backgroundSource, bg, ...metadata } = draft;
    catalog.push({ ...metadata, category: 'birthday', style: 'custom', thumbnail: thumbnailUrl, hasPhoto: false, updatedAt: '2026-10-20T00:00:00Z' });
    await fs.writeFile(path.join(artifacts, `${draft.id}.png`), decode(result.full));
    const pdf = new jsPDF({ orientation: 'portrait', unit: 'mm', format: [127, 177.8], compress: true });
    pdf.addImage(result.full, 'PNG', 0, 0, 127, 177.8);
    await fs.writeFile(path.join(artifacts, `${draft.id}.pdf`), Buffer.from(pdf.output('arraybuffer')));
    const originalBytes = (await fs.stat(path.join(root, `content/birthday-batch/sources/original-${draft.source}.png`))).size;
    const backgroundBytes = (await fs.stat(path.join(root, 'public', backgroundUrl))).size;
    reports.push({ id: draft.id, width: result.width, height: result.height, originalBytes, backgroundBytes, thumbnailBytes: thumbnail.length, reusedBackground: true, reductionPercent: Number(((1 - backgroundBytes / originalBytes) * 100).toFixed(1)), backgroundUrl, thumbnailUrl });
  }
} finally { await browser?.close(); await server.close(); }
await fs.writeFile(path.join(directory, 'asset-ids.json'), JSON.stringify(ids, null, 2) + '\n');
await fs.writeFile(path.join(directory, 'report.json'), JSON.stringify(reports, null, 2) + '\n');
await fs.writeFile(path.join(root, 'src/birthday-collection-assets.js'), `// Generated by content/birthday-collection/prepare.mjs. Backgrounds/fonts are shared.\nexport const birthdayCollectionAssetIds = ${JSON.stringify(ids, null, 2)};\nexport const birthdayCollectionAssets = new Map(${JSON.stringify(assets, null, 2)});\n`);
await fs.writeFile(path.join(root, 'src/birthday-collection-catalog.js'), `// Metadata only; layouts and fonts load when the editor opens.\nexport const birthdayCollectionTemplates = ${JSON.stringify(catalog, null, 2)};\n`);
console.log(JSON.stringify(reports, null, 2));
