import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { batchCatalog, batchAssetIds } from './designs.mjs';

const directory = fileURLToPath(new URL('./', import.meta.url));
const root = path.resolve(directory, '../../..');
const batch = '2026-10-21';
const folder = path.join(root, 'content/robi-batches');
const assetFolder = `assets/pozivnice/robi/${batch}`;
await fs.mkdir(path.join(root, 'public', assetFolder), { recursive: true });
let registry;
try { registry = JSON.parse(await fs.readFile(path.join(folder, 'registry.json'), 'utf8')); }
catch (error) { if (error.code !== 'ENOENT') throw error; registry = []; }
const entries = [], catalog = [];
for (const meta of batchCatalog) {
  const urls = {};
  for (const [kind, file] of [['background', `backgrounds/${meta.id}.webp`], ['thumbnail', `previews/${meta.id}.webp`]]) {
    const bytes = await fs.readFile(path.join(directory, file));
    const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 12);
    const url = `/${assetFolder}/${meta.id}-${kind}-${hash}.webp`;
    await fs.writeFile(path.join(root, 'public', url), bytes);
    entries.push([batchAssetIds.designs[meta.id][kind], url]);
    urls[kind] = url;
  }
  catalog.push({ ...meta, thumbnail: urls.thumbnail });
}
const record = { batch, module: `../content/robi-batches/${batch}/designs.mjs`, assets: batchAssetIds, entries, catalog };
registry = [...registry.filter(entry => entry.batch !== batch), record].sort((a, b) => b.batch.localeCompare(a.batch));
await fs.writeFile(path.join(folder, 'registry.json'), JSON.stringify(registry, null, 2) + '\n');
await fs.writeFile(path.join(root, 'src/robi-assets.js'), `// Generated by Robi register.mjs; static assets only.\nexport const robiAssets = new Map(${JSON.stringify(registry.flatMap(item => item.entries), null, 2)});\n`);
await fs.writeFile(path.join(root, 'src/robi-catalog.js'), `// Metadata only; image files, fonts and layouts load separately.\nexport const robiTemplates = ${JSON.stringify(registry.flatMap(item => item.catalog), null, 2)};\n`);
const imports = registry.map((item, index) => `import { batchDesign as build${index}, batchAssetIds as assets${index} } from '${item.module}';`).join('\n');
const batches = registry.map((_, index) => `{ assets: assets${index}, build: build${index} }`).join(',\n');
await fs.writeFile(path.join(root, 'src/robi-designs.js'), `// Layouts stay outside the initial catalog bundle.\n${imports}\nexport const robiBatches = [${batches}];\n`);
console.log('Registered six Robi templates and twelve optimized assets.');
