// Re-encode the owner's untouched backgrounds and render editable typography.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { createServer } from 'vite';
import { chromium } from 'playwright';
import { jsPDF } from 'jspdf';
import { firstBirthdayExtraDesign } from './designs.mjs';

const folder=fileURLToPath(new URL('./',import.meta.url)),root=path.resolve(folder,'../..');
const metadata=JSON.parse(await fs.readFile(path.join(folder,'metadata.json'),'utf8'));
const ids=JSON.parse(await fs.readFile(path.join(folder,'asset-ids.json'),'utf8'));
const output=path.join(root,'public/assets/pozivnice/prvi-rodjendan-20261029');
const artifacts=path.resolve(root,'../artifacts/birthday-oct29');
await fs.mkdir(output,{recursive:true});await fs.mkdir(artifacts,{recursive:true});
const assets=[],report=[];
const bytes=data=>Buffer.from(data.split(',')[1],'base64');
const hash=data=>createHash('sha256').update(data).digest('hex');
async function asset(id,label,data){
 const name=`${label}-${hash(data).slice(0,12)}.webp`,url=`/assets/pozivnice/prvi-rodjendan-20261029/${name}`;
 await fs.writeFile(path.join(output,name),data);assets.push([id,url]);return url;
}
const server=await createServer({root,server:{host:'127.0.0.1',port:5196,strictPort:true}});
let browser;
try{
 await server.listen();
 browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
 const page=await browser.newPage();await page.goto('http://127.0.0.1:5196/');
 for(const item of metadata){
  const design=firstBirthdayExtraDesign(item.id,{backgroundId:ids.designs[item.id].background,fontIds:ids.fonts});
  const result=await page.evaluate(async({design,source})=>{
   await import('/src/editor.js');
   const {renderDesign,designData,loadDesignFont,layerBounds}=await import('/src/design-renderer.js');
   await Promise.all(design.fonts.map(font=>loadDesignFont(font)));
   await Promise.all(design.layers.map(layer=>document.fonts.load(`${layer.italic?'italic ':''}400 ${layer.size}px "${layer.family}"`,layer.text)));
   const original=new Image();original.src=`/content/first-birthday-extra-20261029/sources/original-${source}.png`;await original.decode();
   const c=document.createElement('canvas');c.width=original.naturalWidth;c.height=original.naturalHeight;c.getContext('2d').drawImage(original,0,0);
   const background=c.toDataURL('image/webp',.94),image=new Image();image.src=background;await image.decode();
   const data=designData(design),prepared={background:image};
   const full=renderDesign(document.createElement('canvas'),design,data,null,1500,prepared).toDataURL('image/png');
   const thumbnail=renderDesign(document.createElement('canvas'),design,data,null,500,prepared).toDataURL('image/webp',.9);
   return {background,full,thumbnail,width:original.naturalWidth,height:original.naturalHeight,bounds:design.layers.map(l=>({id:l.id,field:l.field,x:l.x,y:l.y,rotation:l.rotation,...layerBounds(l,data,c)}))};
  },{design,source:item.source});
  const background=bytes(result.background),thumbnail=bytes(result.thumbnail),full=bytes(result.full);
  const backgroundUrl=await asset(ids.designs[item.id].background,`${item.id}-background`,background);
  const thumbnailUrl=await asset(ids.designs[item.id].thumbnail,`${item.id}-thumbnail`,thumbnail);
  await fs.writeFile(path.join(artifacts,`${item.id}.png`),full);
  const pdf=new jsPDF({orientation:'portrait',unit:'mm',format:[127,177.8],compress:true});pdf.addImage(result.full,'PNG',0,0,127,177.8);await fs.writeFile(path.join(artifacts,`${item.id}.pdf`),Buffer.from(pdf.output('arraybuffer')));
  const original=await fs.readFile(path.join(folder,`sources/original-${item.source}.png`));
  report.push({id:item.id,source:item.source,originalSha256:hash(original),width:result.width,height:result.height,originalBytes:original.length,backgroundBytes:background.length,thumbnailBytes:thumbnail.length,reductionPercent:Number(((1-background.length/original.length)*100).toFixed(1)),backgroundUrl,thumbnailUrl,bounds:result.bounds});
 }
}finally{await browser?.close();await server.close();}
await fs.writeFile(path.join(root,'src/first-birthday-extra-assets.js'),`// Generated by content/first-birthday-extra-20261029/prepare.mjs.\nexport const firstBirthdayExtraAssetIds = ${JSON.stringify(ids,null,2)};\nexport const firstBirthdayExtraAssets = new Map(${JSON.stringify(assets,null,2)});\n`);
await fs.writeFile(path.join(folder,'report.json'),JSON.stringify(report,null,2)+'\n');
const keep=new Set(assets.map(([,url])=>path.basename(url)));
for(const name of await fs.readdir(output)){if(/^(prva-morska-plovidba|labudicev-prvi-ples)-(background|thumbnail)-[a-f0-9]{12}\.webp$/.test(name)&&!keep.has(name))await fs.unlink(path.join(output,name));}
console.log(JSON.stringify(report.map(({bounds,...entry})=>entry),null,2));
